import api from "./api";

const BASE_URL = "/fees/components";

const feeComponentApi = {

    /*
    |--------------------------------------------------------------------------
    | Get all fee components
    |--------------------------------------------------------------------------
    | Optional params:
    | - search
    | - component_type
    | - is_active
    |--------------------------------------------------------------------------
    */

    getAll: (params = {}) =>
        api.get(BASE_URL, {
            params,
        }),


    /*
    |--------------------------------------------------------------------------
    | Get single fee component
    |--------------------------------------------------------------------------
    */

    getById: (id) =>
        api.get(`${BASE_URL}/${id}`),


    /*
    |--------------------------------------------------------------------------
    | Create fee component
    |--------------------------------------------------------------------------
    */

    create: (data) =>
        api.post(BASE_URL, data),


    /*
    |--------------------------------------------------------------------------
    | Update fee component
    |--------------------------------------------------------------------------
    */

    update: (id, data) =>
        api.put(
            `${BASE_URL}/${id}`,
            data
        ),


    /*
    |--------------------------------------------------------------------------
    | Delete fee component
    |--------------------------------------------------------------------------
    */

    delete: (id) =>
        api.delete(
            `${BASE_URL}/${id}`
        ),


    /*
    |--------------------------------------------------------------------------
    | Activate / Deactivate
    |--------------------------------------------------------------------------
    */

    toggleStatus: (id) =>
        api.put(
            `${BASE_URL}/${id}/toggle-status`
        ),

};

export default feeComponentApi;