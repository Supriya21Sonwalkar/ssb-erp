import api from "./api";

const BASE_URL = "/fees/structures";

const feeStructureApi = {

    /*
    |--------------------------------------------------------------------------
    | Get all fee structures
    |--------------------------------------------------------------------------
    | Optional params:
    | search
    | fee_component_id
    | course_id
    | academic_year_id
    | status
    |--------------------------------------------------------------------------
    */

    getAll: (params = {}) =>
        api.get(BASE_URL, {
            params,
        }),


    /*
    |--------------------------------------------------------------------------
    | Get single fee structure
    |--------------------------------------------------------------------------
    */

    getById: (id) =>
        api.get(`${BASE_URL}/${id}`),


    /*
    |--------------------------------------------------------------------------
    | Create fee structure
    |--------------------------------------------------------------------------
    */

    create: (data) =>
        api.post(
            BASE_URL,
            data
        ),


    /*
    |--------------------------------------------------------------------------
    | Update fee structure
    |--------------------------------------------------------------------------
    */

    update: (id, data) =>
        api.put(
            `${BASE_URL}/${id}`,
            data
        ),


    /*
    |--------------------------------------------------------------------------
    | Delete fee structure
    |--------------------------------------------------------------------------
    */

    delete: (id) =>
        api.delete(
            `${BASE_URL}/${id}`
        ),


    /*
    |--------------------------------------------------------------------------
    | Activate / Deactivate
    |--------------------------------------------------------------------------
    */

    toggleStatus: (id) =>
        api.put(
            `${BASE_URL}/${id}/toggle-status`
        ),

};


export default feeStructureApi;