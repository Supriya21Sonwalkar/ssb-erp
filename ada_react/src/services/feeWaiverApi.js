import api from "./api";

const BASE_URL = "/fees/waivers";


export default {

    /*
    |--------------------------------------------------------------------------
    | Get All Waivers
    |--------------------------------------------------------------------------
    */

    getAll: (params = {}) =>
        api.get(BASE_URL, {
            params,
        }),


    /*
    |--------------------------------------------------------------------------
    | Search Students
    |--------------------------------------------------------------------------
    */

    searchStudents: (params = {}) =>
        api.get(`${BASE_URL}/students`, {
            params,
        }),


    /*
    |--------------------------------------------------------------------------
    | Create Waiver
    |--------------------------------------------------------------------------
    */

    create: (data) =>
        api.post(BASE_URL, data),


    /*
    |--------------------------------------------------------------------------
    | Get Single Waiver
    |--------------------------------------------------------------------------
    */

    getById: (id) =>
        api.get(`${BASE_URL}/${id}`),


    /*
    |--------------------------------------------------------------------------
    | Update Waiver
    |--------------------------------------------------------------------------
    */

    update: (id, data) =>
        api.put(`${BASE_URL}/${id}`, data),


    /*
    |--------------------------------------------------------------------------
    | Delete Waiver
    |--------------------------------------------------------------------------
    */

    delete: (id) =>
        api.delete(`${BASE_URL}/${id}`),

};
