import api from "./api";

const BASE_URL = "/homework-assignments";

const homeworkAssignmentApi = {

    /*
    |--------------------------------------------------------------------------
    | Get All Homework
    |--------------------------------------------------------------------------
    */

    getAll: (params = {}) =>
        api.get(BASE_URL, {
            params,
        }),


    /*
    |--------------------------------------------------------------------------
    | Get Single Homework
    |--------------------------------------------------------------------------
    */

    getById: (id) =>
        api.get(`${BASE_URL}/${id}`),


    /*
    |--------------------------------------------------------------------------
    | Create Homework
    |--------------------------------------------------------------------------
    */

    create: (data) =>
        api.post(BASE_URL, data, {
            headers: {
                "Content-Type": "multipart/form-data",
            },
        }),


    /*
    |--------------------------------------------------------------------------
    | Update Homework
    |--------------------------------------------------------------------------
    */

    update: (id, data) =>
        api.post(`${BASE_URL}/${id}`, data, {
            headers: {
                "Content-Type": "multipart/form-data",
            },
        }),


    /*
    |--------------------------------------------------------------------------
    | Delete Homework
    |--------------------------------------------------------------------------
    */

    delete: (id) =>
        api.delete(`${BASE_URL}/${id}`),


    /*
    |--------------------------------------------------------------------------
    | Publish Homework
    |--------------------------------------------------------------------------
    */

    publish: (id) =>
        api.post(`${BASE_URL}/${id}/publish`),


    /*
    |--------------------------------------------------------------------------
    | Close Homework
    |--------------------------------------------------------------------------
    */

    close: (id) =>
        api.post(`${BASE_URL}/${id}/close`),


    /*
    |--------------------------------------------------------------------------
    | Activate Homework
    |--------------------------------------------------------------------------
    */

    activate: (id) =>
        api.post(`${BASE_URL}/${id}/activate`),

};

export default homeworkAssignmentApi;